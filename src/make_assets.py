import sys, io, struct
sys.path.insert(0, '/home/claude/tools')
import fontlib
from PIL import Image
from fontTools import subset
from fontTools.ttLib import TTFont
F = '/home/claude/_extracted/Fonts/'
out = sys.argv[1]
lines = ['// Generated by make_assets.py: fonts and button-prompt icons taken from the game\'s own UI\\FONTS bundles.',
         '// Fonts: traced from the glyph atlases of 535957 (italic labels) and 368865 (regular values), Latin only.',
         '// Icons: glyphs U+E0xx of font 232329 (identical in every font), RGBA, straight alpha.', '#pragma once', '#include <stdint.h>', '']
def arr(name, data):
    lines.append('static const uint8_t %s[%d] = {' % (name, len(data)))
    for i in range(0, len(data), 32):
        lines.append(','.join(str(b) for b in data[i:i+32]) + ',')
    lines.append('};')
caps = {}
for name, path in [('kFontItalic', '535957_Latin_220px/NFSHPR_535957_traced.ttf'), ('kFontRegular', '368865_Latin_106px/NFSHPR_368865_traced.ttf')]:
    f = TTFont(F + path)
    opts = subset.Options(); opts.drop_tables += ['GSUB', 'GPOS']; opts.notdef_outline = True
    s = subset.Subsetter(opts); s.populate(unicodes=list(range(0x20, 0x180))); s.subset(f)
    b = io.BytesIO(); f.save(b); data = b.getvalue()
    g = f['glyf'][f.getBestCmap()[ord('H')]]
    caps[name] = g.yMax / 1000.0
    print(name, len(data), 'cap', caps[name])
    arr(name, data)
lines.append('static const float kFontItalicCapEm = %.4ff, kFontRegularCapEm = %.4ff;' % (caps['kFontItalic'], caps['kFontRegular']))

fl = fontlib.load('/mnt/user-data/uploads/Need For Speed Hot Pursuit Remastered/UI/FONTS/232329.BNDL')
G = {g['cp']: g for g in fl['glyphs'] if g['valid']}
def crop(cp):
    im = fl['img'].crop(G[cp]['box'])
    bb = im.getbbox()
    return im.crop(bb), G[cp]['unk']
icons = [('IconPadView', 0xE042), ('IconPadA', 0xE022), ('IconPadB', 0xE023), ('IconPadLB', 0xE03B), ('IconPadRB', 0xE03E),
         ('IconDpadUpDown', 0xE036), ('IconDpadLeftRight', None), ('IconKeyUp', 0xE06C), ('IconKeyDown', 0xE06D),
         ('IconKeyLeft', 0xE06E), ('IconKeyRight', 0xE06F), ('IconKeyEnter', 0xE06B), ('IconKeycapLeft', 0xE047),
         ('IconKeycapMiddle', 0xE048), ('IconKeycapRight', 0xE049)]
ref, refs = crop(0xE022)
refH = ref.height * refs / 1000.0   # Xbox A as the game draws it = 1.0
lines += ['', 'enum IconId {'] + ['    %s,' % n for n, _ in icons] + ['    kIconCount', '};',
          '// rel = display height relative to the Xbox A button (the game\'s own per-glyph scale)',
          'struct IconData { int w, h; float rel; const uint8_t* rgba; };']
total = 0; recs = []
for n, cp in icons:
    if cp is None:  # D-pad left/right: the game has no such glyph; the up/down one turned by 90 degrees
        im, sc = crop(0xE036); im = im.rotate(90, expand=True)
    else:
        im, sc = crop(cp)
    rel = im.height * sc / 1000.0 / refH
    # store at most 1.6x the largest size the overlay can draw (A button = 40 px at the 44 px font limit)
    maxh = int(round(40 * rel * 1.6))
    if n == 'IconKeycapMiddle':
        im = im.resize((max(1, im.width), min(im.height, maxh)), Image.LANCZOS)
    elif im.height > maxh:
        im = im.resize((max(1, round(im.width * maxh / im.height)), maxh), Image.LANCZOS)
    data = im.convert('RGBA').tobytes(); total += len(data)
    arr('kIcon_' + n, data)
    recs.append('{%d, %d, %.4ff, kIcon_%s}' % (im.width, im.height, rel, n))
    print(n, im.size, 'rel %.3f' % rel)
lines.append('static const IconData kIcons[kIconCount] = {' + ', '.join(recs) + '};')
open(out, 'w').write('\n'.join(lines) + '\n')
print('icons bytes', total)
